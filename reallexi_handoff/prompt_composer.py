"""The identity firewall.

This is the module that actually answers "don't lose the characters".

The rule is simple and absolute: **the language model never writes identity or voice.**
It writes motion. Identity and voice text is assembled here, deterministically, from the
cast registry, and pasted byte-identically into every single shot of the film. Because the
text is generated by string formatting rather than by a model, shot 1 and shot 40 receive
character descriptions that are literally the same bytes — there is nothing left for
drift to act on at the prompt level.

``lock_signature`` hashes those blocks so the pipeline can assert, per shot, that nothing
mutated between composition and execution.
"""
from __future__ import annotations

import hashlib
from typing import Any, Dict, List, Optional

FORBIDDEN = (
    "no on-screen text, no watermark, no logo, no subtitles, no border, no split screen, "
    "no scene cuts, no new characters, no character swap, no age change, no outfit change, "
    "no style change, no extra limbs, no deformed hands, no duplicate faces"
)


def identity_block(characters: List[Dict[str, Any]]) -> str:
    """Verbatim, ordered, byte-stable description of everyone in the shot."""
    lines = ["[IDENTITY_LOCK]",
             "These characters already exist and are fixed. Reproduce them exactly as written. "
             "Do not reinterpret, do not restyle, do not age, do not redesign. "
             "Only pose, gesture, expression, held objects and camera may change."]
    for ch in characters:
        token = ch.get("trigger_token", "")
        lines.append(
            f"- {ch['name']} ({token}): {ch['identity_line'].rstrip('.')}. "
            f"Build: {ch.get('build','as reference')}. Hair: {ch.get('hair','as reference')}. "
            f"Eyes: {ch.get('eyes','as reference')}. Skin: {ch.get('skin','as reference')}. "
            f"Wardrobe: {ch.get('wardrobe','as reference')}. "
            f"Distinguishing marks: {ch.get('face_marks','none')}. "
            f"Always carries or wears: {ch.get('signature_prop','nothing additional')}. "
            f"Colour palette: {', '.join(ch.get('palette', []) or ['as reference'])}. "
            f"Moves like this: {ch.get('motion_signature','naturally')}."
        )
        never = ch.get("never") or []
        if never:
            lines.append(f"  NEVER for {ch['name']}: " + "; ".join(never) + ".")
    return "\n".join(lines)


def voice_block(characters: List[Dict[str, Any]]) -> str:
    """Verbatim voice identity. Same bytes in every shot keeps the cast sounding the same."""
    lines = ["[VOICE_LOCK]",
             "Each character keeps one single voice for the entire film. The voice established "
             "in the opening shot is the only voice they ever have. Never recast, never "
             "re-pitch, never change accent, never add a narrator."]
    for ch in characters:
        v = ch.get("voice", {}) or {}
        lines.append(
            f"- {ch['name']} speaks with a {v.get('timbre','warm')} timbre, "
            f"pitched {v.get('pitch','mid')}, at a {v.get('pace','steady')} pace, "
            f"{v.get('accent','neutral')} accent, default emotion {v.get('default_emotion','calm')}. "
            f"Speech quirk: {v.get('quirk','none')}. "
            f"Signature sound: {v.get('signature_sound','none')}. "
            f"Voice seed {ch.get('audio_seed','fixed')}."
        )
    lines.append("Lip movement must match every spoken syllable. Mouth shapes follow the words.")
    return "\n".join(lines)


def continuity_block(scene: Dict[str, Any], previous: Optional[Dict[str, Any]], first_frame_note: str) -> str:
    lines = ["[CONTINUITY]"]
    if previous:
        lines.append(
            f"This shot continues directly from shot {previous['index']} "
            f"(\"{previous['title']}\"). Carried over: "
            f"{str(scene.get('continuity_from_previous','')).rstrip('.')}. "
            f"The previous shot ended with: {str(previous.get('transition_out','')).rstrip('.')}."
        )
    else:
        lines.append("Opening shot of the film. Establish the world calmly.")
    lines.append(
        f"Location: {scene.get('location','')}. Time: {scene.get('time_of_day','')}. "
        f"Weather and light: {scene.get('weather','')}."
    )
    lines.append(f"[FIRST_FRAME] {first_frame_note}")
    return "\n".join(lines)


def audio_block(scene: Dict[str, Any], characters: List[Dict[str, Any]]) -> str:
    by_id = {c["id"]: c for c in characters}
    lines = ["[AUDIO]"]
    dialogue = scene.get("dialogue") or []
    if dialogue:
        for d in dialogue:
            spk = by_id.get(d.get("speaker"), {})
            name = spk.get("name", d.get("speaker", "character"))
            v = spk.get("voice", {}) or {}
            lines.append(
                f'- {name} says, in their established {v.get("timbre","warm")} '
                f'{v.get("pitch","mid")} voice ({d.get("delivery","natural")}): "{d.get("line","")}"'
            )
    else:
        lines.append("- No dialogue in this shot. Characters communicate through movement only.")
    amb = scene.get("ambience") or []
    if amb:
        lines.append("- Ambient sound: " + ", ".join(amb) + ".")
    if scene.get("music"):
        lines.append(f"- Music: {scene['music']}. Motion follows the musical energy.")
    lines.append("- Sound is continuous with the previous shot. No audio cut, no silence gap.")
    return "\n".join(lines)


def compose(
    scene: Dict[str, Any],
    characters: List[Dict[str, Any]],
    motion_paragraph: str,
    bible: Dict[str, Any],
    previous: Optional[Dict[str, Any]] = None,
    first_frame_note: str = "The supplied start image is frame 0 and must not change. All motion begins after frame 0.",
) -> str:
    """Assemble the final LTX prompt for one shot."""
    style = bible.get("visual_style", "cinematic")
    palette = ", ".join(bible.get("colour_palette", []) or [])
    parts = [
        identity_block(characters),
        "",
        voice_block(characters),
        "",
        continuity_block(scene, previous, first_frame_note),
        "",
        "[SHOT]",
        f"Shot {scene.get('index','?')} — {scene.get('title','')}. "
        f"Camera: {scene.get('camera','static, then a slow push in')}.",
        motion_paragraph.strip(),
        "",
        audio_block(scene, characters),
        "",
        "[STYLE]",
        f"{style}. Palette: {palette}. Consistent lighting and grade with every other shot in the film.",
        "",
        "[FORBIDDEN]",
        FORBIDDEN + ".",
    ]
    return "\n".join(parts).strip()


def lock_signature(characters: List[Dict[str, Any]]) -> str:
    """Hash of the locked blocks. Identical across every shot, or something went wrong."""
    payload = identity_block(characters) + "\n" + voice_block(characters)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def verify(prompt: str, characters: List[Dict[str, Any]]) -> None:
    """Fail loudly if a locked block did not survive into the final prompt."""
    problems = []
    for block, label in ((identity_block(characters), "IDENTITY_LOCK"),
                         (voice_block(characters), "VOICE_LOCK")):
        if block not in prompt:
            problems.append(label)
    for ch in characters:
        if ch["identity_line"].rstrip(".") not in prompt:
            problems.append(f"identity_line:{ch['id']}")
        if ch.get("trigger_token") and ch["trigger_token"] not in prompt:
            problems.append(f"trigger_token:{ch['id']}")
    if problems:
        raise ValueError(f"Locked blocks missing from composed prompt: {problems}")


def negative_prompt(bible: Dict[str, Any]) -> str:
    base = ("pc game, console game, video game, cartoon, childish, ugly, "
            "text, watermark, logo, subtitles, extra limbs, deformed hands, "
            "face morph, character swap, outfit change, style change, flicker, "
            "scene cut, duplicate character, blurry")
    extra = bible.get("negative_extra", "")
    return f"{base}, {extra}".strip().rstrip(",")
